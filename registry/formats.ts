export type FormatId = (typeof FORMATS)[number]['id'];

const formatMap = new Map(FORMATS.map((f) => [f.id, f]));

export function getFormat(id: string): Format | undefined {
  return formatMap.get(id);
}

export function requireFormat(id: string): Format {
  const f = formatMap.get(id);
  if (!f) throw new Error(`Unknown format ID: "${id}"`);
  return f;
}
